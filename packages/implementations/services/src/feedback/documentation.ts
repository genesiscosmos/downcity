/** Feedback API 的静态注册文档；字段、长度和状态语义与服务校验保持一致。 */
import type { ApiDocumentation } from "@downcity/downtown";
import { object_schema as obj, items_schema, text_schema as text, enum_schema, time_schema } from "../shared/documentation.js";

const status = enum_schema("open", "reviewing", "replied", "closed");
const feedback_id = text("Feedback ID generated by send");
const message = { type: "string", minLength: 1, maxLength: 10000 };
const query = { status, limit: { type: ["integer", "string"], description: "Converted to an integer; invalid/nonpositive values use 100, values above the endpoint cap are clamped", default: 100 } };
const record = obj({ feedback_id, city_id: { type: ["string", "null"] }, user_id: text("Submitting user"), message, contact: text("Optional contact, empty when omitted"), status, reply: text("Official reply, initially empty"), reply_by: text("Reply author, initially empty"), replied_at: time_schema, metadata_json: text("Serialized meta JSON"), created_at: time_schema, updated_at: time_schema });
const errors = [{ status: 400, description: "Invalid text length, status or filter" }, { status: 401, description: "A valid user or admin credential is required as declared by this route" }];

/** 每个公开入口的专属请求、响应和公开示例。 */
export const feedback_documentation: Record<string, ApiDocumentation> = {
  "/send": {
    description: "Submit feedback for the authenticated user; city_id is attribution only. Stores feedback without sending external notifications.",
    request_schema: obj({ message, contact: { type: "string", maxLength: 500 }, meta: { type: ["object", "array", "string", "number", "boolean", "null"], description: "Any serializable JSON metadata; stored as metadata_json" } }, ["message"]),
    response_schema: obj({ feedback_id, status: { const: "open" }, created_at: time_schema }), errors,
    examples: [{ name: "Submit a suggestion", request: { message: "Please add keyboard navigation." }, response: { feedback_id: "feedback_example", status: "open", created_at: "2026-11-19T00:00:00.000Z" } }],
  },
  "/me": {
    description: "Read the current user's feedback, newest first. Other user_id and city_id filters are ignored. Limit defaults to 100 and is capped at 200.",
    request_schema: obj({ ...query, limit: { ...query.limit, description: "Converted to an integer; invalid/nonpositive uses 100, capped at 200" } }, []), response_schema: items_schema(record), errors,
    examples: [{ name: "My open feedback", request: { status: "open", limit: 20 }, response: { items: [] } }],
  },
  "/messages": {
    description: "Admin: filter feedback by exact city, user and status, newest first. Limit defaults to 100 and is capped at 500.",
    request_schema: obj({ ...query, city_id: { type: "string", minLength: 1, maxLength: 500 }, user_id: text("Exact user filter") }, []), response_schema: items_schema(record), errors,
    examples: [{ name: "Review queue", request: { status: "reviewing", limit: 100 }, response: { items: [] } }],
  },
  "/reply": {
    description: "Admin: replace the official reply and set status to replied; does not send a notification.",
    request_schema: obj({ feedback_id, reply: message, reply_by: { type: "string", maxLength: 200, default: "admin" } }, ["feedback_id", "reply"]),
    response_schema: obj({ feedback_id, status: { const: "replied" }, replied_at: time_schema }), errors: [...errors, { status: 404, description: "Feedback does not exist" }],
    examples: [{ name: "Reply", request: { feedback_id: "feedback_example", reply: "Keyboard navigation is available." } }],
  },
  "/status": {
    description: "Admin: update processing status without changing the stored reply.",
    request_schema: obj({ feedback_id, status }), response_schema: obj({ feedback_id, status, updated_at: time_schema }), errors: [...errors, { status: 404, description: "Feedback does not exist" }],
    examples: [{ name: "Close feedback", request: { feedback_id: "feedback_example", status: "closed" } }],
  },
};
