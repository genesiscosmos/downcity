/** 默认英文文案，也可用于纯函数的标题回退。 */
export const default_control_translate: ChatControlTranslate = (key, values) => {
  const template = messages[key] ?? key;
  return template.replace(/\{\{?(\w+)\}?\}/g, (match, name: string) => values?.[name] === undefined ? match : String(values[name]));
};
const control_messages_context = createContext<ChatControlTranslate>(default_control_translate);
/** 每个组合边界继承上层文案，独用时可覆盖。 */
export function ControlMessagesProvider({ translate, children }: ControlMessagesProviderProps) {
  const inherited = useContext(control_messages_context);
  return <control_messages_context.Provider value={translate ?? inherited}>{children}</control_messages_context.Provider>;
}
/** 与宿主无关的命名空间文案解析。 */
export function use_control_translation(namespace?: string): ChatControlTranslate {
  const translate = useContext(control_messages_context);
  return (key, values) => translate(namespace && !key.includes(":") ? `${namespace}:${key}` : key, values);
}
